"""Convert a registered SPSA surface to a Colosseum tune file.

`tools/spsa_configs/config_<group>.json` states each coordinate's engine default,
range and `step`, the b43 step that is the unit of "a step" in every reading.
Colosseum's tune file states `c_end`, the perturbation at the END of the
horizon, so the two differ by that run's own decay:

    c_end = perturbation * N ** -gamma          gamma = 0.102

A tune is one run to a registered ceiling, read at checkpoints (PLAN rule 7c):

    python tools/spsa_config_to_colosseum.py d71fit --rule7c --ceiling 6000
    python tools/spsa_config_to_colosseum.py d71fit --rule7c --ceiling 6000 --check

The perturbation is two steps where the seed has two steps of room inside its
range, otherwise the largest from one to two steps that the room allows; a
coordinate with under one step of room keeps one step and is named. `c_end`
is rounded down, so the runner's first perturbation never exceeds the room
and no first arm plays clamped. The run file sets rule 7c's gain ratio,
r_end 0.00155. The room report goes to stdout for the registration.

`--iterations N` writes the earlier block form (the step itself as the
perturbation, the gain ratio of spsa-tune.toml or schedule_<group>.json). It
is kept so the historical groups' committed files still `--check`; a new
tune is registered with `--rule7c`.

Writes (or checks) `tools/spsa_configs/colosseum/<group>.tune.toml`, the ordered
parameter vector, and `<group>.run.toml`, a run file that extends the tune policy
and applies `fixed_<group>.json` as fixed options on both arms.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import pathlib
import sys

GAMMA = 0.102
RULE7C_R_END = 0.00155
ROOT = pathlib.Path(__file__).resolve().parent
CONFIGS = ROOT / "spsa_configs"
OUT = CONFIGS / "colosseum"
POLICY = ROOT / "colosseum" / "spsa-tune.toml"


def tune_file(group: str, surface: dict, iterations: int) -> str:
    decay = iterations ** -GAMMA
    lines = [
        f"# Generated by tools/spsa_config_to_colosseum.py from config_{group}.json",
        f"# at N = {iterations} iterations; c_end = step * N ** -{GAMMA}.",
        "# Regenerate rather than edit: --check fails when the two disagree.",
    ]
    for name, spec in surface.items():
        c_end = spec["step"] * decay
        lines += [
            "",
            "[[parameters]]",
            f'name = "{name}"',
            f"initial = {spec['value']}",
            f"min = {spec['min_value']}",
            f"max = {spec['max_value']}",
            f"c_end = {c_end:.4f}",
        ]
    return "\n".join(lines) + "\n"


def graded_perturbation(start: int, minimum: int, maximum: int, step: float) -> tuple[float, float]:
    """(perturbation in steps, room in steps): two steps where the seed has the
    room, otherwise the largest from one to two that stays inside the range,
    never under one step."""
    room = min(start - minimum, maximum - start) / step
    return min(2.0, max(1.0, room)), room


def rule7c_tune_file(group: str, surface: dict, ceiling: int) -> tuple[str, list[str]]:
    """A rule 7c tune file for a run of `ceiling` iterations, and its room report."""
    decay = ceiling ** -GAMMA
    lines = [
        f"# Generated by tools/spsa_config_to_colosseum.py --rule7c from config_{group}.json.",
        f"# rule 7c ceiling N = {ceiling}; perturbation = graded steps (two where the seed has",
        f"# the room); c_end = perturbation * step * N ** -{GAMMA}, rounded down. r_end {RULE7C_R_END}.",
        "# Regenerate rather than edit: --check fails when the two disagree.",
    ]
    report = []
    for name, spec in surface.items():
        start, minimum, maximum = int(spec["value"]), int(spec["min_value"]), int(spec["max_value"])
        step = float(spec["step"])
        steps, room = graded_perturbation(start, minimum, maximum, step)
        note = None
        if room < 2.0:
            note = ("under one step of room: one step, named" if room < 1.0
                    else "1 step" if steps == 1.0 else f"{steps:g} steps")
            report.append(f"{name}: seed {start} in [{minimum}, {maximum}], step {step:g}, "
                          f"room {room:.2f} steps -> {note}")
        lines += [
            "",
            "[[parameters]]",
            f'name = "{name}"',
            f"initial = {start}",
            f"min = {minimum}",
            f"max = {maximum}",
            # Rounded down: the runner recovers c0 = c_end * N ** gamma, and a
            # c0 above the room would play its first arm clamped.
            f"c_end = {math.floor(steps * step * decay * 1e4) / 1e4:.4f}",
        ]
        if note:
            lines.append(f"# room {room:.2f} steps at the seed: {note}")
    return "\n".join(lines) + "\n", report


def policy_path(out: pathlib.Path) -> str:
    """The tune policy as the run file in `out` must name it: relative where it
    can be (the default directory reads ../../colosseum/spsa-tune.toml),
    absolute across drives."""
    try:
        return pathlib.Path(os.path.relpath(POLICY, out)).as_posix()
    except ValueError:
        return POLICY.resolve().as_posix()


def run_file(group: str, fixed: dict, horizon: str, r_end: float | None = None, out: pathlib.Path = OUT) -> str:
    options = ", ".join(f'"{name}={value}"' for name, value in fixed.items())
    # The gain ratio is spsa-tune.toml's unless the registration sets its own
    # (that file says so); a set ratio is written here so the run file carries it.
    ratio = f"r-end = {r_end:g}\n" if r_end is not None else ""
    ratio_note = f"# The registration sets the gain ratio r-end = {r_end:g}.\n" if r_end is not None else ""
    return (
        f"# Generated by tools/spsa_config_to_colosseum.py from fixed_{group}.json.\n"
        f"# The surface is config_{group}.json converted at {horizon}.\n"
        f"{ratio_note}"
        "# Supply the engine, --total-games, --seed and --dir on the command line.\n"
        "\n"
        f'extend = "{policy_path(out)}"\n'
        'unset = ["/options/option"]\n'
        "\n"
        "[options]\n"
        f'tune = "{group}.tune.toml"\n'
        f"option = [{options}]\n"
        f"{ratio}"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("group", help="surface name, as in config_<group>.json")
    horizon = parser.add_mutually_exclusive_group(required=True)
    horizon.add_argument("--rule7c", action="store_true", help="one run to --ceiling, read at checkpoints (PLAN rule 7c)")
    horizon.add_argument("--iterations", type=int, help="a historical group's registered block horizon N")
    parser.add_argument("--ceiling", type=int, help="rule 7c's registered ceiling in iterations")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    parser.add_argument("--out", type=pathlib.Path, default=OUT,
                        help="directory of the tune and run files (default: tools/spsa_configs/colosseum)")
    parser.add_argument(
        "--r-end",
        type=float,
        default=None,
        help="block form only: must equal schedule_<group>.json's r_end; the ratio itself is read from that file",
    )
    args = parser.parse_args()
    if args.rule7c:
        if args.ceiling is None or args.ceiling < 1:
            parser.error("--rule7c needs a positive --ceiling")
        if args.r_end is not None:
            parser.error(f"--rule7c sets r_end {RULE7C_R_END}; --r-end belongs to the block form")
    else:
        if args.ceiling is not None:
            parser.error("--ceiling belongs to --rule7c")
        if args.iterations < 1:
            parser.error("--iterations must be positive")
    if args.r_end is not None and not 0 < args.r_end < 1:
        parser.error("--r-end must lie in (0, 1)")

    surface_path = CONFIGS / f"config_{args.group}.json"
    fixed_path = CONFIGS / f"fixed_{args.group}.json"
    if not surface_path.is_file():
        parser.error(f"no surface at {surface_path}")
    surface = json.loads(surface_path.read_text(encoding="utf-8"))
    fixed = json.loads(fixed_path.read_text(encoding="utf-8")) if fixed_path.is_file() else {}
    # A block registration that set its own gain ratio committed it beside the
    # group as schedule_<group>.json ({"r_end": ...}).
    schedule_path = CONFIGS / f"schedule_{args.group}.json"
    schedule = json.loads(schedule_path.read_text(encoding="utf-8")) if schedule_path.is_file() else {}
    r_end = schedule.get("r_end")
    if r_end is not None and not 0 < float(r_end) < 1:
        parser.error(f"{schedule_path}: r_end must lie in (0, 1)")

    report: list[str] = []
    if args.rule7c:
        if r_end is not None:
            parser.error(f"{schedule_path} sets a block-form ratio; a rule 7c group runs at r_end {RULE7C_R_END}")
        tune_text, report = rule7c_tune_file(args.group, surface, args.ceiling)
        run_text = run_file(args.group, fixed, f"the rule 7c ceiling N = {args.ceiling}", RULE7C_R_END, args.out)
        label = f"the rule 7c ceiling N = {args.ceiling}"
    else:
        if args.r_end is not None:
            if r_end is None:
                parser.error(f"--r-end given but {schedule_path} does not exist; commit the ratio there")
            if abs(float(r_end) - args.r_end) > 1e-12:
                parser.error(f"--r-end {args.r_end} differs from {schedule_path}'s {r_end}")
        tune_text = tune_file(args.group, surface, args.iterations)
        run_text = run_file(args.group, fixed, f"N = {args.iterations}", r_end, args.out)
        label = f"N = {args.iterations}"

    written = {
        args.out / f"{args.group}.tune.toml": tune_text,
        args.out / f"{args.group}.run.toml": run_text,
    }
    for line in report:
        print(f"room: {line}")
    if args.check:
        stale = [
            path
            for path, want in written.items()
            if not path.is_file() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != want
        ]
        for path in stale:
            print(f"stale or missing: {path}", file=sys.stderr)
        if stale:
            return 1
        print(f"{len(written)} files current for {args.group} at {label}")
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
    for path, text in written.items():
        # The tree is CRLF; newline='' keeps the text exactly as written.
        path.write_text(text.replace("\n", "\r\n"), encoding="utf-8", newline="")
        print(f"wrote {path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
